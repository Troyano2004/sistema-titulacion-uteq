-- ============================================================================
-- V9 — Control de oportunidades/reprobación, justificaciones y casos
--      especiales, y calendario unificado de titulación
--      (Módulos 13, 14 y 18)
-- ============================================================================

-- ── Módulo 13 — Oportunidades y reprobación ─────────────────────────────────
CREATE TABLE registro_oportunidad (
    id_registro                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante                    INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    id_periodo                       INTEGER NOT NULL REFERENCES periodo_titulacion(id_periodo),
    modalidad                        VARCHAR(35) NOT NULL,
    tipo_oportunidad                 VARCHAR(15) NOT NULL,
    resultado                        VARCHAR(15) NOT NULL,
    calificacion                     NUMERIC(4,2),
    fecha                            DATE NOT NULL,
    observaciones                    TEXT,
    autorizacion_tercera_matricula   BOOLEAN NOT NULL DEFAULT FALSE,
    resolucion_tercera_matricula     VARCHAR(200)
);
CREATE INDEX idx_registro_oportunidad_estudiante ON registro_oportunidad(id_estudiante);
CREATE INDEX idx_registro_oportunidad_estudiante_periodo ON registro_oportunidad(id_estudiante, id_periodo);

CREATE TABLE actualizacion_conocimientos (
    id_actualizacion              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante                  INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    fecha_solicitud                TIMESTAMP NOT NULL DEFAULT now(),
    estado                          VARCHAR(15) NOT NULL DEFAULT 'SOLICITADA',
    resolucion_consejo_directivo   VARCHAR(200),
    fecha_aprobacion               DATE,
    periodo_original               VARCHAR(20) NOT NULL,
    periodo_actualizacion          VARCHAR(20)
);
CREATE INDEX idx_actualizacion_conocimientos_estudiante ON actualizacion_conocimientos(id_estudiante);

CREATE TABLE actualizacion_conocimientos_asignatura (
    id_actualizacion  BIGINT NOT NULL REFERENCES actualizacion_conocimientos(id_actualizacion) ON DELETE CASCADE,
    asignatura        VARCHAR(150) NOT NULL
);
CREATE INDEX idx_actualizacion_asignatura ON actualizacion_conocimientos_asignatura(id_actualizacion);

CREATE TABLE autorizacion_tercera_matricula (
    id_autorizacion       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante          INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    id_periodo              INTEGER NOT NULL REFERENCES periodo_titulacion(id_periodo),
    resolucion              VARCHAR(200) NOT NULL,
    fecha_autorizacion      DATE NOT NULL DEFAULT CURRENT_DATE,
    id_usuario_autoriza    INTEGER NOT NULL REFERENCES usuario(id_usuario),
    CONSTRAINT uq_autorizacion_estudiante_periodo UNIQUE (id_estudiante, id_periodo)
);

-- ── Módulo 14 — Justificaciones y casos especiales ──────────────────────────
CREATE TABLE feriado_academico (
    id_feriado    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha         DATE NOT NULL,
    descripcion   VARCHAR(150) NOT NULL,
    CONSTRAINT uq_feriado_fecha UNIQUE (fecha)
);

CREATE TABLE solicitud_justificacion (
    id_solicitud                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante                 INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    tipo                           VARCHAR(30) NOT NULL,
    motivo                        TEXT NOT NULL,
    documento_adjunto_id          BIGINT,
    tipo_documento                VARCHAR(30),
    fecha_evento                  TIMESTAMP NOT NULL,
    fecha_solicitud               TIMESTAMP NOT NULL DEFAULT now(),
    fecha_limite                  TIMESTAMP,
    estado                         VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    id_usuario_resuelve           INTEGER REFERENCES usuario(id_usuario),
    fecha_resolucion              TIMESTAMP,
    nueva_fecha_programada        DATE,
    observaciones_resolucion      TEXT
);
CREATE INDEX idx_solicitud_justificacion_estudiante ON solicitud_justificacion(id_estudiante);
CREATE INDEX idx_solicitud_justificacion_estado_limite ON solicitud_justificacion(estado, fecha_limite);

-- ── Módulo 18 — Aval de Unidad de Registro ──────────────────────────────────
ALTER TABLE periodo_titulacion ADD COLUMN aval_unidad_registro BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE periodo_titulacion ADD COLUMN fecha_aval           DATE;
ALTER TABLE periodo_titulacion ADD COLUMN avalado_por          VARCHAR(150);
