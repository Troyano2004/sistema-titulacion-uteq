-- ============================================================================
-- V18 — Mueve la estructura de secciones del TIC (Art. 42/43/44/45) de un
-- switch hardcodeado en Java (SeccionPlantillaProvider) a una tabla, para
-- que la estructura de cada modalidad quede definida en la BD y no como una
-- constante en el código.
--
-- De paso corrige un error real: el Art. 59 exige que, después de la
-- Portada, TODA modalidad de TIC (Proyecto de Investigación, Proyecto
-- Tecnológico, Estudio de Caso y Artículo Científico) lleve Certificación
-- del Director, Autoría, Dedicatoria y Agradecimiento — pero
-- SeccionPlantillaProvider solo las incluía para Proyecto de Investigación
-- (Art. 42), porque los Arts. 44/45 no las repiten en su propio listado. El
-- Art. 59 es el que manda qué se entrega para sustentación, así que las
-- otras 3 modalidades quedaban generando documentos incompletos. También se
-- corrige Artículo Científico, al que le faltaban las secciones que SÍ
-- comparten las 4 modalidades (Certificación, Autoría, Índice, Código
-- Dublín, Anexos) — el Art. 43 no define estructura propia porque remite a
-- la normativa de la revista, pero los preliminares del Art. 59 sí aplican.
-- ============================================================================

CREATE TABLE seccion_plantilla_tic (
    id_seccion_plantilla   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_plantilla          VARCHAR(30) NOT NULL,
    codigo_seccion          VARCHAR(50) NOT NULL,
    titulo                  VARCHAR(150) NOT NULL,
    orden                   INTEGER NOT NULL,
    obligatoria             BOOLEAN NOT NULL DEFAULT TRUE,
    auto_llenada            BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (tipo_plantilla, codigo_seccion)
);
CREATE INDEX idx_seccion_plantilla_tic_tipo ON seccion_plantilla_tic(tipo_plantilla, orden);

