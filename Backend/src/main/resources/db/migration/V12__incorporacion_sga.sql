CREATE TABLE titulo_profesional (
    id_titulo                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante               INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    id_acta                      INTEGER NOT NULL UNIQUE REFERENCES acta_grado(id_acta),
    numero_titulo                VARCHAR(50),
    fecha_emision                 DATE,
    registro_senescyt             VARCHAR(100),
    fecha_registro_senescyt       DATE,
    estado                          VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE'
);
CREATE INDEX idx_titulo_profesional_est ON titulo_profesional(id_estudiante);

-- ── Módulo 20: importación manual del SGA ───────────────────────────────────
CREATE TABLE pensum_importado (
    id_pensum_importado   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante          INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    codigo_asignatura       VARCHAR(30) NOT NULL,
    nombre_asignatura       VARCHAR(200) NOT NULL,
    calificacion             NUMERIC(4,2),
    estado                    VARCHAR(15) NOT NULL,
    periodo_academico        VARCHAR(20),
    fecha_importacion        TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_pensum_importado_est ON pensum_importado(id_estudiante);

CREATE TABLE requisito_importado (
    id_requisito_importado          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante                     INTEGER NOT NULL UNIQUE REFERENCES estudiante(id_estudiante),
    idioma_aprobado                    BOOLEAN NOT NULL DEFAULT FALSE,
    practicas_laborales_aprobadas      BOOLEAN NOT NULL DEFAULT FALSE,
    horas_practicas                     INTEGER,
    servicio_comunitario_aprobado       BOOLEAN NOT NULL DEFAULT FALSE,
    horas_servicio                       INTEGER,
    fecha_importacion                    TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE deuda_importada (
    id_deuda_importada   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante          INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    tipo_deuda               VARCHAR(100) NOT NULL,
    monto                     NUMERIC(10,2),
    estado                     VARCHAR(15) NOT NULL,
    fecha_importacion          TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_deuda_importada_est ON deuda_importada(id_estudiante);

CREATE TABLE importacion_sga_log (
    id_log                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                     VARCHAR(15) NOT NULL,
    nombre_archivo            VARCHAR(300),
    total_filas                INTEGER NOT NULL DEFAULT 0,
    filas_ok                    INTEGER NOT NULL DEFAULT 0,
    filas_error                  INTEGER NOT NULL DEFAULT 0,
    errores                        TEXT,
    id_usuario_importa            INTEGER REFERENCES usuario(id_usuario),
    fecha_importacion              TIMESTAMP NOT NULL DEFAULT now()
);
