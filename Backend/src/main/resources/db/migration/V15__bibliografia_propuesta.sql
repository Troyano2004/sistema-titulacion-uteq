-- ============================================================================
-- V15 — Referencias bibliográficas de la PROPUESTA de titulación (Art. 46:
-- mínimo 10 referencias, 60% con antigüedad <= 5 años, validado al crear la
-- propuesta). Tabla separada de referencia_bibliografica (que pertenece al
-- documento_tic, una etapa posterior): la propuesta no tiene todavía un
-- documento_tic asociado en el momento de su creación.
-- ============================================================================

CREATE TABLE referencia_bibliografica_propuesta (
    id_referencia       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propuesta        INTEGER NOT NULL REFERENCES propuesta_titulacion(id_propuesta) ON DELETE CASCADE,
    autores              VARCHAR(500) NOT NULL,
    titulo               VARCHAR(400) NOT NULL,
    anio_publicacion     INTEGER NOT NULL,
    fuente               VARCHAR(400),
    tipo                 VARCHAR(15) NOT NULL
);
CREATE INDEX idx_referencia_bibliografica_propuesta ON referencia_bibliografica_propuesta(id_propuesta);
