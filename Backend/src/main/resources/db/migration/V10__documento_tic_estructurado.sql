-- ============================================================================
-- V10 — Editor de documento del TIC por secciones estructuradas
--
-- Modelo NUEVO y en PARALELO a documento_titulacion (que se mantiene sin
-- cambios: Dt2Service, AntiplagioCompilatioService, TitulacionWorkflowService,
-- RevisionIAService, CierreTitulacion y AvalDirector siguen dependiendo de
-- esa tabla para el pipeline de antiplagio/predefensa/sustentación). No hay
-- FK cruzada entre ambos modelos — se migran manualmente más adelante.
-- ============================================================================

CREATE TABLE documento_tic (
    id_documento_tic              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante                  INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    id_tipo_trabajo                 INTEGER NOT NULL REFERENCES tipo_trabajo_titulacion(id_tipo_trabajo),
    id_director                     INTEGER REFERENCES docente(id_docente),
    modalidad_entrega               VARCHAR(20) NOT NULL,
    estado                           VARCHAR(15) NOT NULL DEFAULT 'BORRADOR',
    titulo                          VARCHAR(300),
    ciudad                           VARCHAR(100) DEFAULT 'Quevedo',
    fecha_creacion                  TIMESTAMP NOT NULL DEFAULT now(),
    fecha_ultima_modificacion       TIMESTAMP NOT NULL DEFAULT now(),
    archivo_pdf_url                 VARCHAR(500)
);
CREATE INDEX idx_documento_tic_estudiante ON documento_tic(id_estudiante);

CREATE TABLE seccion_documento_tic (
    id_seccion          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_tic     BIGINT NOT NULL REFERENCES documento_tic(id_documento_tic) ON DELETE CASCADE,
    codigo_seccion       VARCHAR(50) NOT NULL,
    titulo               VARCHAR(150) NOT NULL,
    contenido_html       TEXT,
    orden                INTEGER NOT NULL,
    obligatoria          BOOLEAN NOT NULL DEFAULT TRUE,
    auto_llenada         BOOLEAN NOT NULL DEFAULT FALSE,
    estado               VARCHAR(15) NOT NULL DEFAULT 'VACIO',
    CONSTRAINT uq_seccion_documento_codigo UNIQUE (id_documento_tic, codigo_seccion)
);
CREATE INDEX idx_seccion_documento_tic_doc ON seccion_documento_tic(id_documento_tic);

CREATE TABLE version_documento_tic (
    id_version           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_tic      BIGINT NOT NULL REFERENCES documento_tic(id_documento_tic) ON DELETE CASCADE,
    numero_version        INTEGER NOT NULL,
    fecha_version         TIMESTAMP NOT NULL DEFAULT now(),
    creada_por            VARCHAR(200) NOT NULL,
    contenido_snapshot    TEXT NOT NULL
);
CREATE INDEX idx_version_documento_tic_doc ON version_documento_tic(id_documento_tic);

CREATE TABLE comentario_documento_tic (
    id_comentario         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_tic       BIGINT NOT NULL REFERENCES documento_tic(id_documento_tic) ON DELETE CASCADE,
    id_seccion             BIGINT REFERENCES seccion_documento_tic(id_seccion),
    id_usuario_autor       INTEGER NOT NULL REFERENCES usuario(id_usuario),
    rol_autor               VARCHAR(25) NOT NULL,
    contenido               TEXT NOT NULL,
    fecha_creacion          TIMESTAMP NOT NULL DEFAULT now(),
    resuelto                 BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_comentario_documento_tic_doc ON comentario_documento_tic(id_documento_tic);

CREATE TABLE referencia_bibliografica (
    id_referencia         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_tic       BIGINT NOT NULL REFERENCES documento_tic(id_documento_tic) ON DELETE CASCADE,
    autores                VARCHAR(500) NOT NULL,
    titulo                 VARCHAR(400) NOT NULL,
    anio_publicacion       INTEGER NOT NULL,
    fuente                 VARCHAR(400),
    tipo                    VARCHAR(15) NOT NULL
);
CREATE INDEX idx_referencia_bibliografica_doc ON referencia_bibliografica(id_documento_tic);
