-- ============================================================================
-- V11 — Expediente digital y catálogo de documentos habilitantes (Módulo 15)
--
-- Modelo NUEVO y en PARALELO a documento_habilitante (que se mantiene sin
-- cambios: DocumentoHabilitanteService sigue usando su catálogo hardcodeado
-- para el flujo de habilitación ya vigente del Director). Este catálogo es
-- el expediente institucional completo (20 documentos TIC A-T, 15 Complexivo
-- A-O) validado por Secretaría-Abogacía, no solo los 4-6 que valida el
-- Director.
-- ============================================================================

CREATE TABLE catalogo_documento_habilitante (
    id_catalogo    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(5) NOT NULL,
    nombre         VARCHAR(300) NOT NULL,
    descripcion    TEXT,
    modalidad      VARCHAR(15) NOT NULL,
    orden          INTEGER NOT NULL,
    obligatorio    BOOLEAN NOT NULL DEFAULT TRUE,
    responsable    VARCHAR(20) NOT NULL,
    id_facultad    INTEGER REFERENCES facultad(id_facultad)
);
CREATE INDEX idx_catalogo_documento_modalidad ON catalogo_documento_habilitante(modalidad);

CREATE TABLE expediente_estudiante (
    id_expediente        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante         INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    modalidad              VARCHAR(15) NOT NULL,
    periodo_titulacion     VARCHAR(20),
    estado                  VARCHAR(15) NOT NULL DEFAULT 'INCOMPLETO',
    fecha_creacion          TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_expediente_estudiante_est ON expediente_estudiante(id_estudiante);

CREATE TABLE documento_expediente (
    id_documento_expediente   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_expediente              BIGINT NOT NULL REFERENCES expediente_estudiante(id_expediente) ON DELETE CASCADE,
    id_catalogo                 BIGINT NOT NULL REFERENCES catalogo_documento_habilitante(id_catalogo),
    estado                        VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    archivo_url                  VARCHAR(500),
    observaciones                 TEXT,
    id_usuario_valida            INTEGER REFERENCES usuario(id_usuario),
    fecha_validacion              TIMESTAMP,
    motivo_rechazo                TEXT
);
CREATE INDEX idx_documento_expediente_exp ON documento_expediente(id_expediente);
CREATE INDEX idx_documento_expediente_estado ON documento_expediente(estado);

