-- ============================================================================
-- V8 — Examen Complexivo real (Módulos 12 y 17)
--
-- Construye desde cero el motor del examen complexivo de 100 preguntas:
--   - Planificación de ejes temáticos (BORRADOR -> APROBADO_COMITE_ACADEMICO)
--   - Banco de preguntas (pregunta_complexivo / opcion_pregunta)
--   - Aplicación del examen (examen_complexivo_aplicacion /
--     examen_complexivo_respuesta), con temporizador y calificación de
--     servidor, y delegados de supervisión (delegado_examen).
--
-- No toca las tablas del flujo de tutoría del informe práctico
-- (complexivo_titulacion / complexivo_informe_practico / complexivo_tutoria,
-- ahora servidas por InformePracticoService) ni la entidad huérfana
-- examen_complexivo (ExamenComprensivo.java), que se deja intacta.
-- ============================================================================

-- ── Planificación de ejes temáticos (TAREA 1.1) ─────────────────────────────
ALTER TABLE eje_tematico ADD COLUMN cronograma TEXT;
ALTER TABLE eje_tematico ADD COLUMN contenidos_tematicos TEXT;
ALTER TABLE eje_tematico ADD COLUMN estado_planificacion VARCHAR(30);
ALTER TABLE eje_tematico ADD COLUMN fecha_planificacion TIMESTAMP;
ALTER TABLE eje_tematico ADD COLUMN fecha_aprobacion_planificacion TIMESTAMP;
ALTER TABLE eje_tematico ADD COLUMN id_usuario_aprobador_planificacion INTEGER
    REFERENCES usuario(id_usuario);

-- ── Banco de preguntas (TAREA 2) ────────────────────────────────────────────
CREATE TABLE pregunta_complexivo (
    id_pregunta         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_eje_tematico     INTEGER NOT NULL REFERENCES eje_tematico(id_eje_tematico),
    id_carrera          INTEGER NOT NULL REFERENCES carrera(id_carrera),
    enunciado           TEXT NOT NULL,
    dificultad          VARCHAR(15) NOT NULL,
    estado              VARCHAR(15) NOT NULL DEFAULT 'EN_REVISION',
    id_docente_creador  INTEGER NOT NULL REFERENCES docente(id_docente),
    fecha_creacion      TIMESTAMP NOT NULL DEFAULT now(),
    periodo_academico   VARCHAR(20) NOT NULL
);
CREATE INDEX idx_pregunta_complexivo_carrera_estado ON pregunta_complexivo(id_carrera, estado);
CREATE INDEX idx_pregunta_complexivo_eje_estado ON pregunta_complexivo(id_eje_tematico, estado);

CREATE TABLE opcion_pregunta (
    id_opcion    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pregunta  BIGINT NOT NULL REFERENCES pregunta_complexivo(id_pregunta) ON DELETE CASCADE,
    texto        TEXT NOT NULL,
    es_correcta  BOOLEAN NOT NULL DEFAULT FALSE,
    orden        INTEGER NOT NULL
);
CREATE INDEX idx_opcion_pregunta_pregunta ON opcion_pregunta(id_pregunta);

-- ── Aplicación del examen (TAREA 3) ─────────────────────────────────────────
CREATE TABLE examen_complexivo_aplicacion (
    id_aplicacion               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante                INTEGER NOT NULL REFERENCES estudiante(id_estudiante),
    id_periodo                   INTEGER NOT NULL REFERENCES periodo_titulacion(id_periodo),
    tipo                          VARCHAR(15) NOT NULL,
    fecha_programada             DATE NOT NULL,
    hora_inicio                  TIMESTAMP,
    hora_fin                     TIMESTAMP,
    duracion_minutos             INTEGER NOT NULL DEFAULT 180,
    estado                        VARCHAR(15) NOT NULL DEFAULT 'PROGRAMADO',
    calificacion                  NUMERIC(4,2),
    total_preguntas_correctas    INTEGER,
    id_docente_delegado          INTEGER REFERENCES docente(id_docente),
    observaciones                 TEXT,
    documento_identidad          VARCHAR(30),
    firmado_compromisos_eticos   BOOLEAN NOT NULL DEFAULT FALSE,
    hora_ingreso                  TIMESTAMP
);
CREATE INDEX idx_examen_complexivo_estudiante_periodo ON examen_complexivo_aplicacion(id_estudiante, id_periodo);
CREATE INDEX idx_examen_complexivo_estado_horafin ON examen_complexivo_aplicacion(estado, hora_fin);

CREATE TABLE examen_complexivo_respuesta (
    id_respuesta            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aplicacion            BIGINT NOT NULL REFERENCES examen_complexivo_aplicacion(id_aplicacion) ON DELETE CASCADE,
    id_pregunta               BIGINT NOT NULL REFERENCES pregunta_complexivo(id_pregunta),
    id_opcion_seleccionada   BIGINT REFERENCES opcion_pregunta(id_opcion),
    orden                     INTEGER NOT NULL,
    CONSTRAINT uq_respuesta_aplicacion_pregunta UNIQUE (id_aplicacion, id_pregunta)
);
CREATE INDEX idx_respuesta_aplicacion ON examen_complexivo_respuesta(id_aplicacion);

CREATE TABLE delegado_examen (
    id_delegado_examen  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aplicacion        BIGINT NOT NULL REFERENCES examen_complexivo_aplicacion(id_aplicacion) ON DELETE CASCADE,
    id_docente            INTEGER NOT NULL REFERENCES docente(id_docente),
    id_carrera            INTEGER NOT NULL REFERENCES carrera(id_carrera),
    fecha_asignacion      TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_delegado_examen_aplicacion ON delegado_examen(id_aplicacion);
