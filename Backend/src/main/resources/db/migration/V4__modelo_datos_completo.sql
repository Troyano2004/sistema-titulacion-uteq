-- ============================================================================
-- V2 — Modelo de datos completo (Reglamento UIC-UTEQ)
--
-- Amplía el modelo base (V1) con los campos y entidades exigidos por el
-- reglamento que todavía no estaban cubiertos: datos de discapacidad y
-- nivel del estudiante, vinculación/posgrado del docente, estándar
-- bibliográfico de la facultad, ejes temáticos, líneas de investigación y
-- matrícula de titulación. También siembra los roles institucionales.
--
-- Todas las columnas nuevas son NULLABLE o tienen DEFAULT: no se pierde ni
-- se invalida ningún registro existente. Esta migración solo agrega — no
-- elimina ni renombra columnas existentes.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Campos nuevos en entidades existentes
-- ----------------------------------------------------------------------------

ALTER TABLE estudiante ADD COLUMN nivel_semestre          INTEGER;
ALTER TABLE estudiante ADD COLUMN carnet_conadis           VARCHAR(30);
ALTER TABLE estudiante ADD COLUMN porcentaje_discapacidad  INTEGER;

ALTER TABLE docente ADD COLUMN tipo_vinculacion   VARCHAR(20);
ALTER TABLE docente ADD COLUMN nivel_posgrado     VARCHAR(20);
ALTER TABLE docente ADD COLUMN area_conocimiento  VARCHAR(200);

ALTER TABLE facultad ADD COLUMN estandar_bibliografico VARCHAR(20);

-- ----------------------------------------------------------------------------
-- 2. Entidades nuevas
-- ----------------------------------------------------------------------------

CREATE TABLE eje_tematico (
    id_eje_tematico        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrera             INTEGER NOT NULL,
    nombre                 VARCHAR(200) NOT NULL,
    descripcion            TEXT,
    id_docente_responsable INTEGER,
    periodo_academico      VARCHAR(20) NOT NULL,
    estado                 VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE linea_investigacion (
    id_linea_investigacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrera              INTEGER NOT NULL,
    nombre                  VARCHAR(200) NOT NULL,
    descripcion             TEXT,
    estado                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',
    fecha_aprobacion        DATE
);

CREATE TABLE matricula_titulacion (
    id_matricula             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante            INTEGER NOT NULL,
    periodo_academico        VARCHAR(20) NOT NULL,
    nivel                    VARCHAR(20) NOT NULL,
    id_opcion_titulacion     INTEGER NOT NULL,
    id_subtipo_trabajo       INTEGER,
    fecha_matricula          TIMESTAMP NOT NULL,
    estado                   VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',
    numero_cambios_opcion    INTEGER NOT NULL DEFAULT 0,
    motivo_ultimo_cambio     TEXT,
    fecha_ultimo_cambio      TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 3. Llaves foráneas de las entidades nuevas
-- ----------------------------------------------------------------------------

ALTER TABLE eje_tematico ADD CONSTRAINT fk_ejetematico_carrera FOREIGN KEY (id_carrera) REFERENCES carrera (id_carrera);
ALTER TABLE eje_tematico ADD CONSTRAINT fk_ejetematico_docente FOREIGN KEY (id_docente_responsable) REFERENCES docente (id_docente);

ALTER TABLE linea_investigacion ADD CONSTRAINT fk_lineainvestigacion_carrera FOREIGN KEY (id_carrera) REFERENCES carrera (id_carrera);

ALTER TABLE matricula_titulacion ADD CONSTRAINT fk_matricula_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante (id_estudiante);
ALTER TABLE matricula_titulacion ADD CONSTRAINT fk_matricula_opcion FOREIGN KEY (id_opcion_titulacion) REFERENCES modalidad_titulacion (id_modalidad);
ALTER TABLE matricula_titulacion ADD CONSTRAINT fk_matricula_subtipo FOREIGN KEY (id_subtipo_trabajo) REFERENCES tipo_trabajo_titulacion (id_tipo_trabajo);

-- ----------------------------------------------------------------------------
-- 4. Roles del sistema — Reglamento UIC-UTEQ
--    Siembra los roles institucionales (DECANO nuevo, SECRETARIO_ABOGADO y
--    DIRECCION_ACADEMICA ya usados por backend/frontend desde la
--    reconstrucción de seguridad). Sobre una base de datos nueva esto es
--    solo un INSERT; los UPDATE de abajo son defensivos por si existieran
--    registros con los nombres de rol antiguos.
-- ----------------------------------------------------------------------------

INSERT INTO roles_sistema (nombre_rol)
SELECT v.nombre_rol
FROM (VALUES
    ('ADMIN'),
    ('ESTUDIANTE'),
    ('DOCENTE'),
    ('DOCENTE_TITULADO'),
    ('COORDINADOR'),
    ('DECANO'),
    ('SECRETARIO_ABOGADO'),
    ('DIRECCION_ACADEMICA'),
    ('GESTOR_USUARIOS'),
    ('ROL_REPORT')
) AS v(nombre_rol)
WHERE NOT EXISTS (
    SELECT 1 FROM roles_sistema r WHERE r.nombre_rol = v.nombre_rol
);

-- Migra registros existentes que aún usen los nombres de rol antiguos
-- (SECRETARIO/ABOGADO fusionados en SECRETARIO_ABOGADO;
--  DIRECTOR_ADMINISTRATIVO renombrado a DIRECCION_ACADEMICA). Actualiza
-- tanto la columna de texto (rol/rol_asignado) como la FK id_rol para que
-- ambas queden consistentes con roles_sistema.
UPDATE usuario SET rol = 'SECRETARIO_ABOGADO' WHERE rol IN ('SECRETARIO', 'ABOGADO');
UPDATE usuario SET rol_asignado = 'SECRETARIO_ABOGADO' WHERE rol_asignado IN ('SECRETARIO', 'ABOGADO');
UPDATE usuario SET rol = 'DIRECCION_ACADEMICA' WHERE rol = 'DIRECTOR_ADMINISTRATIVO';
UPDATE usuario SET rol_asignado = 'DIRECCION_ACADEMICA' WHERE rol_asignado = 'DIRECTOR_ADMINISTRATIVO';

UPDATE usuario u SET id_rol = r.id_rol
FROM roles_sistema r
WHERE r.nombre_rol = u.rol_asignado
  AND u.rol_asignado IN ('SECRETARIO_ABOGADO', 'DIRECCION_ACADEMICA')
  AND u.id_rol <> r.id_rol;
